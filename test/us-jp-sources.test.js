'use strict';
const {it}=require('node:test'),assert=require('node:assert/strict');
const fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {getSource,listSources,lookupSource,classifyLink}=require('../src/fabric/registry');
const {RawArtifactStore}=require('../src/fabric/artifacts');
const {SourceConnector}=require('../src/fabric/connector');
const {normalizeArtifact}=require('../src/fabric/normalizer');
const {buildResearchBrief}=require('../src/ai/researchBrief');
it('US/JP official families route synthetic retrieval without legal interpretation',async t=>{
 assert.ok(listSources('JP').length>=3);
 assert.equal(getSource('JP-NTA').authorityName,'Japan National Tax Agency');
 assert.equal(getSource('JP-MOF').authorityName,'Japan Ministry of Finance');
 assert.equal(getSource('US-TREASURY').authorityName,'United States Department of the Treasury');
 assert.equal(lookupSource('JP','https://www.nta.go.jp/taxes/').sourceId,'JP-NTA');
 assert.equal(lookupSource('JP','https://www.mof.go.jp/tax_policy/').sourceId,'JP-MOF');
 assert.equal(lookupSource('JP','https://laws.e-gov.go.jp/law/340AC0000000033').sourceId,'JP-EGOV');
 assert.equal(getSource('JP-EGOV').baseUrl,'https://laws.e-gov.go.jp/');
 assert.equal(lookupSource('US','https://home.treasury.gov/policy-issues/tax-policy'),null);
 assert.equal(lookupSource('US','https://www.treasury.gov/resource-center/tax-policy/').sourceId,'US-TREASURY');
 assert.equal(classifyLink('JP','https://www.nta.go.jp.evil.example/'),'REJECTED_SOURCE');
 assert.equal(classifyLink('JP','https://law.e-gov.go.jp/'),'UNREGISTERED_OFFICIAL_SOURCE_CANDIDATE');
 const root=fs.mkdtempSync(path.join(os.tmpdir(),'bigm-usjp-'));t.after(()=>fs.rmSync(root,{recursive:true,force:true}));
 const store=new RawArtifactStore(root);
 const body='<html><body><p>Synthetic portal page for routing test only.</p></body></html>';
 const c=new SourceConnector({store,fetchImpl:async()=>new Response(body,{status:200,headers:{'content-type':'text/html'}})});
 const artifact=await c.retrieve({sourceId:'JP-NTA',url:'https://www.nta.go.jp/taxes/'});
 assert.equal(artifact.status,'DISCOVERED');
 const envelope=normalizeArtifact(store,artifact);
 assert.equal(envelope.provenance.rawContentHash.length,64);
 assert.equal(envelope.processingState,'NORMALIZED');
 const brief=buildResearchBrief({objective:'Synthetic routing check',confirmedFacts:[],unknownFacts:[],taxPeriod:{periodStart:'2026-01-01',periodEnd:'2026-12-31'},jurisdictions:['US','JP'],questionsToResolve:['Which official portals are registered?'],maxTurns:2,maxRetrievals:2});
 assert.deepEqual(brief.jurisdictions,['US','JP']);
 assert.ok(brief.preferredAllowedSources.find(j=>j.jurisdiction==='JP').localSearch.languages.includes('ja'));
 assert.ok(brief.preferredAllowedSources.find(j=>j.jurisdiction==='US').localSearch.languages.includes('en'));
});
